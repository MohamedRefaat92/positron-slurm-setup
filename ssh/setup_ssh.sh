#!/usr/bin/env bash
# setup_ssh.sh — Configure SSH for seamless access to HPC clusters from Positron
#
# What this script does:
#   1. Generates an Ed25519 key pair (if one does not already exist)
#   2. Copies the public key to each cluster so password-less login works
#   3. Writes a ~/.ssh/config block with per-host settings
#
# Usage:
#   chmod +x setup_ssh.sh
#   ./setup_ssh.sh
#
# Prerequisites:
#   - ssh-keygen, ssh-copy-id, and ssh available on PATH
#   - You can reach each host (VPN / on-site network if required)
# ---------------------------------------------------------------------------

set -euo pipefail

KEY="$HOME/.ssh/id_ed25519"
SSH_CONFIG="$HOME/.ssh/config"

# Your accounts: edit these before running (the examples show the format).
BMRC_USER="YOUR_BMRC_USERNAME"        # e.g. abc123
LUDWIG_USER="YOUR_LUDWIG_USERNAME"    # e.g. jdoe
LUDWIG_HOST="YOUR_LUDWIG_HOST"        # IP address or host name, e.g. 192.0.2.10

if [[ "$BMRC_USER $LUDWIG_USER $LUDWIG_HOST" == *YOUR_* ]]; then
    echo "Edit BMRC_USER, LUDWIG_USER and LUDWIG_HOST at the top of $0 first" >&2
    echo "(remove the lines for clusters you don't use)." >&2
    exit 1
fi

# ---------------------------------------------------------------------------
# 1. Generate key pair
# ---------------------------------------------------------------------------
if [[ ! -f "$KEY" ]]; then
    echo "[1/3] Generating Ed25519 key pair at $KEY …"
    ssh-keygen -t ed25519 -C "$(whoami)@$(hostname)" -f "$KEY" -N ""
    echo "      Public key: $(cat "${KEY}.pub")"
else
    echo "[1/3] Key already exists at $KEY — skipping generation."
fi

# Add to ssh-agent / macOS Keychain
eval "$(ssh-agent -s)" > /dev/null
ssh-add --apple-use-keychain "$KEY" 2>/dev/null \
    || ssh-add "$KEY" 2>/dev/null \
    || true

# ---------------------------------------------------------------------------
# 2. Copy public key to each cluster
#    Comment out hosts you do not have access to yet.
# ---------------------------------------------------------------------------
echo ""
echo "[2/3] Copying public key to clusters …"
echo "      You will be prompted for your password / 2FA on each host."
echo ""

# Your clusters (accounts are set at the top of this script)
CLUSTERS=(
    "${BMRC_USER}@cluster1.bmrc.ox.ac.uk"   # BMRC (Oxford)
    "${LUDWIG_USER}@${LUDWIG_HOST}"         # Ludwig cluster
    # "jsmith@login.hpc.university.edu"   # Example: university HPC
    # "user@login.aws-hpc.example.com"    # Example: cloud HPC
)

for TARGET in "${CLUSTERS[@]}"; do
    echo "  → $TARGET"
    ssh-copy-id -i "${KEY}.pub" "$TARGET" || {
        echo "    WARNING: Could not copy key to $TARGET — skipping."
    }
done

# ---------------------------------------------------------------------------
# 3. Write SSH config block
# ---------------------------------------------------------------------------
echo ""
echo "[3/3] Writing SSH config to $SSH_CONFIG …"

# Back up existing config
if [[ -f "$SSH_CONFIG" ]]; then
    cp "$SSH_CONFIG" "${SSH_CONFIG}.bak.$(date +%Y%m%d_%H%M%S)"
    echo "      Existing config backed up."
fi

# Only append the block if it is not already present
if grep -q "# === positron-slurm-setup ===" "$SSH_CONFIG" 2>/dev/null; then
    echo "      Config block already present — skipping."
else
    # Unquoted EOF: the account variables are filled in; \$ keeps a literal $ for ssh.
    cat >> "$SSH_CONFIG" << EOF

# === positron-slurm-setup ===
# Generated by setup_ssh.sh — edit values to match your accounts.

# ── Global defaults ──────────────────────────────────────────────────────────
Host *
    ServerAliveInterval 60      # send keepalive every 60 s
    ServerAliveCountMax 3       # drop after 3 missed keepalives
    AddKeysToAgent yes          # add decrypted keys to ssh-agent automatically
    UseKeychain yes             # macOS: load passphrase from Keychain (remove on Linux)
    IdentityFile ~/.ssh/id_ed25519

# ── BMRC cluster (Oxford) ────────────────────────────────────────────────────
# Two-factor auth site: Positron uses BatchMode=yes and cannot prompt for 2FA.
# ControlMaster keeps an authenticated socket open so Positron reuses it.
# Workflow: open a terminal, run "ssh bmrc_cluster", then connect from Positron.
Host bmrc_cluster
    HostName cluster1.bmrc.ox.ac.uk
    User ${BMRC_USER}
    ControlMaster auto
    ControlPath ~/.ssh/cm-%r@%h:%p
    ControlPersist yes

# BMRC compute node reached via a user-sshd SLURM job (see remote-side setup).
Host bmrc_compute
    User ${BMRC_USER}
    HostKeyAlias bmrc_compute
    ProxyCommand bash -c 'read n p < <(ssh -n bmrc_cluster cat .ssh/userd/current_node); exec ssh -W \$n:\$p bmrc_cluster'

# ── Ludwig cluster ────────────────────────────────────────────────────────────
Host ludwig_cluster
    HostName ${LUDWIG_HOST}
    User ${LUDWIG_USER}
    # ControlMaster not required here because Ludwig accepts key-only auth,
    # so Positron's BatchMode=yes works without a pre-opened socket.

# ── Hypothetical: university HPC with password + OTP ─────────────────────────
# Same pattern as BMRC: ControlMaster lets Positron skip interactive auth.
# Host uni_hpc
#     HostName login.hpc.university.edu
#     User jsmith
#     ControlMaster auto
#     ControlPath ~/.ssh/cm-%r@%h:%p
#     ControlPersist yes

# ── Hypothetical: cloud HPC (AWS ParallelCluster / GCP / Azure) ───────────────
# Key-only auth is standard on cloud; no ControlMaster needed.
# Host cloud_hpc
#     HostName login.aws-hpc.example.com
#     User ec2-user
#     IdentityFile ~/.ssh/cloud_hpc_key     # separate key if desired

# ── Hypothetical: jump-host / bastion pattern ─────────────────────────────────
# Reach an internal node through a public-facing login node.
# Host internal_node
#     HostName 10.0.1.50
#     User researcher
#     ProxyJump bastion.example.com

# === end positron-slurm-setup ===
EOF
    echo "      Config block written."
fi

echo ""
echo "Done. Next steps:"
echo "  1. Open a terminal and run:  ssh bmrc_cluster"
echo "     Complete 2FA — this opens the shared control socket."
echo "  2. Connect from Positron — it reuses the socket, no 2FA needed."
echo "  3. For clusters with key-only auth (Ludwig, cloud), Positron connects"
echo "     directly without a pre-opened terminal session."
